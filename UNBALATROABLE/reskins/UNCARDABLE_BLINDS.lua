        SMODS["Blind"]:take_ownership("bl_eye", {
            atlas = "bl_eye_anim",
            pos = {x = 0, y = 0},
            calculate = function(self, blind, context)
                if blind.disabled then return end
                if context.setting_blind then
                    blind.effects.hand = {}
                    for _, poker_hand in ipairs(G.handlist) do
                        blind.effect.hands[poker_hand] = false
                    end
                end
                if context.debuff_hand then
                    if blind.effects.hands[context.scoring_name] then
                        blind.triggered = true 
                        return {
                            debuff = true
                        }
                    end
                    if not context.check then
                        blind.effect.hands[context.scoring_name] = true
                    end
                end
            end,
            loc_vars = function(self, info_queue, card)
                info_queue[#info_queue+1] = localize("extras_crash_warning")
                return info_queue
            end,
        }, true)
    end]]
