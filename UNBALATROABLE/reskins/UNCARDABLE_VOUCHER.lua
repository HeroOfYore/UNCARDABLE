if not UNCARDABLE.config.disabled then
    for vchr, data in pairs(G.UNCARDABLE_Vouchers1) do
        if data.anim ~= nil then
            SMODS["Voucher"]:take_ownership(vchr, {atlas = vchr .. "_anim",
            pos = {x = 0, y = 0},
            artist_credits = data.artist,
        }, true)
        else
            SMODS["Voucher"]:take_ownership(vchr, {atlas = "unvouchable",
            pos = {x = 0 + data.pos, y = 0},
            artist_credits = data.artist,
        }, true)
        end
    end
    SMODS.Voucher:take_ownership("v_hieroglyph", {
        atlas = "v_hieroglyph_anim",
        pos = {x = 0, y = 0},
        artist_credits = {"heroofyore"},
        set_sprites = function(self, card, front)
            local randomposweighted = math.random(0, 2)
            card.children.center:set_sprite_pos({x= 0, y = randomposweighted})
        end
    }, true)
end